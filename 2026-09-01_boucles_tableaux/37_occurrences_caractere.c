/*
** EXERCICE : Compter les occurrences d'un caractère
**
** Écrire un programme en langage C qui demande à l'utilisateur
** de saisir une chaîne de caractères puis un caractère.
**
** Le programme doit compter combien de fois le caractère choisi
** apparaît dans la chaîne.
**
** EXEMPLE :
**
** Entrée :
** Chaîne : programmation
** Caractère : m
**
** Sortie :
** Le caractère 'm' apparaît 2 fois.
**
** AUTRE EXEMPLE :
**
** Entrée :
** Chaîne : bonjour
** Caractère : o
**
** Sortie :
** Le caractère 'o' apparaît 2 fois.
**
** CONTRAINTES :
**
** - Déclarer un tableau de caractères pour stocker la chaîne.
** - Demander une chaîne à l'utilisateur.
** - Demander le caractère à rechercher.
** - Parcourir la chaîne caractère par caractère avec une boucle.
** - Comparer chaque caractère avec le caractère recherché.
** - Utiliser une variable compteur.
** - Incrémenter le compteur à chaque occurrence trouvée.
** - Afficher le nombre total d'occurrences.
**
** OBJECTIF :
**
** Apprendre à parcourir une chaîne de caractères et à rechercher
** un caractère précis à l'aide d'une boucle et d'une condition.
**
** BONUS :
**
** - Faire la différence entre majuscules et minuscules.
** - Faire une version qui ignore la casse.
** - Créer une fonction compter_occurrences().
** - Afficher la position de chaque occurrence trouvée.
*/