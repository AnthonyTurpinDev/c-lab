/*
** EXERCICE : Factorielle
**
** Écrire un programme en langage C qui demande à l'utilisateur
** de saisir un nombre entier positif N.
**
** Le programme doit calculer et afficher la factorielle de N.
**
** RAPPEL :
**
** La factorielle de N, notée N!, correspond au produit
** de tous les entiers compris entre 1 et N.
**
** Exemple :
**
** 5! = 5 x 4 x 3 x 2 x 1
** 5! = 120
**
** EXEMPLES :
**
** Entrée :
** 5
**
** Sortie :
** 5! = 120
**
** AUTRE EXEMPLE :
**
** Entrée :
** 3
**
** Sortie :
** 3! = 6
**
** CAS PARTICULIER :
**
** 0! = 1
**
** CONTRAINTES :
**
** - Demander un nombre entier positif N.
** - Utiliser une boucle pour effectuer les multiplications.
** - Utiliser une variable pour stocker progressivement
**   le résultat.
** - Initialiser correctement la variable de résultat.
** - Ne pas utiliser de fonction permettant de calculer
**   directement la factorielle.
** - Afficher le résultat final avec printf.
**
** OBJECTIF :
**
** Comprendre le principe d'accumulation par multiplication
** et pratiquer l'utilisation des boucles.
**
** BONUS :
**
** - Faire une version avec une boucle while.
** - Gérer les nombres négatifs.
** - Créer une fonction factorielle() qui reçoit N
**   en paramètre et retourne le résultat.
*/