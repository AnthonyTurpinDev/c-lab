/*
** EXERCICE : Somme, minimum et maximum d'un tableau
**
** Écrire un programme en langage C qui permet de travailler
** avec un tableau d'entiers.
**
** Le programme doit :
**
** - calculer la somme de tous les éléments du tableau ;
** - trouver le plus petit élément du tableau ;
** - trouver le plus grand élément du tableau.
**
** EXEMPLE :
**
** Tableau :
** 12 5 8 20 3 15
**
** Sortie :
** Somme : 63
** Minimum : 3
** Maximum : 20
**
** CONTRAINTES :
**
** - Déclarer un tableau d'entiers.
** - Initialiser le tableau avec plusieurs valeurs.
** - Utiliser une boucle pour parcourir le tableau.
** - Utiliser une variable pour calculer la somme.
** - Utiliser une variable pour mémoriser le minimum.
** - Utiliser une variable pour mémoriser le maximum.
** - Comparer chaque élément avec le minimum et le maximum
**   actuels.
** - Afficher les trois résultats avec printf.
** - Ne pas utiliser de fonction toute faite pour trouver
**   directement le minimum ou le maximum.
**
** OBJECTIF :
**
** Apprendre à parcourir un tableau avec une boucle et à effectuer
** plusieurs traitements sur ses éléments lors d'un même parcours.
**
** BONUS :
**
** - Demander la taille du tableau à l'utilisateur.
** - Demander les valeurs du tableau à l'utilisateur.
** - Calculer également la moyenne.
** - Afficher la position du minimum et du maximum.
*/