/*
** EXERCICE : Deuxième plus grand élément
**
** Écrire un programme en langage C qui permet de trouver
** le deuxième plus grand élément d'un tableau d'entiers.
**
** EXEMPLE :
**
** Tableau :
** 12 5 8 20 3 15
**
** Sortie :
** Le plus grand élément est : 20
** Le deuxième plus grand élément est : 15
**
** AUTRE EXEMPLE :
**
** Tableau :
** 4 10 7 15 2
**
** Sortie :
** Le deuxième plus grand élément est : 10
**
** CONTRAINTES :
**
** - Déclarer un tableau d'entiers.
** - Initialiser le tableau avec plusieurs valeurs.
** - Utiliser une boucle pour parcourir le tableau.
** - Trouver le plus grand élément du tableau.
** - Trouver le deuxième plus grand élément.
** - Ne pas trier le tableau.
** - Ne pas utiliser de deuxième tableau.
** - Gérer correctement les valeurs négatives.
**
** ATTENTION :
**
** Si le tableau ne contient pas au moins deux valeurs distinctes,
** le programme doit afficher un message indiquant qu'il est
** impossible de trouver un deuxième plus grand élément distinct.
**
** EXEMPLE :
**
** Tableau :
** 7 7 7
**
** Sortie :
** Aucun deuxième plus grand élément distinct.
**
** OBJECTIF :
**
** Apprendre à maintenir plusieurs valeurs importantes pendant
** le parcours d'un tableau et améliorer sa logique de comparaison.
**
** BONUS :
**
** - Faire l'exercice en un seul parcours du tableau.
** - Demander la taille et les valeurs du tableau à l'utilisateur.
** - Créer une fonction qui retourne le deuxième plus grand élément.
*/