/*
** EXERCICE : Minimum
**
** Écrire un programme en langage C qui demande à l'utilisateur
** combien de nombres il souhaite saisir.
**
** Le programme doit ensuite demander chaque nombre et déterminer
** le plus petit nombre parmi toutes les valeurs saisies.
**
** EXEMPLE :
**
** Entrée :
** Combien de nombres ? 5
**
** Nombres :
** 12
** 7
** 25
** 3
** 18
**
** Sortie :
** Le minimum est : 3
**
** CONTRAINTES :
**
** - Demander le nombre de valeurs à saisir.
** - Utiliser une boucle pour saisir les nombres un par un.
** - Utiliser une variable pour mémoriser le minimum.
** - Comparer chaque nouveau nombre avec le minimum actuel.
** - Mettre à jour le minimum lorsqu'un nombre plus petit
**   est trouvé.
** - Afficher le minimum à la fin du programme.
** - Gérer le cas où l'utilisateur saisit 0 comme nombre
**   de valeurs.
**
** OBJECTIF :
**
** Apprendre à rechercher la plus petite valeur dans un ensemble
** de nombres en utilisant une boucle et des conditions.
**
** BONUS :
**
** - Trouver également le maximum.
** - Afficher la position du minimum.
** - Tester avec des nombres négatifs.
*/