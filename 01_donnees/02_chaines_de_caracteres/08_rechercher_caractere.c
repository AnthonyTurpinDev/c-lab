/*
** EXERCICE : Rechercher un caractère
**
** CONSIGNE :
**
** Demande à l'utilisateur :
**
** - une chaîne de caractères ;
** - un caractère à rechercher.
**
** Puis parcours la chaîne et vérifie si le caractère
** recherché existe dans celle-ci.
**
** Exemple :
**
**     Chaîne : ordinateur
**     Caractère : d
**
** Résultat attendu :
**
**     Le caractère existe.
**
** Si le caractère n'existe pas :
**
**     Le caractère n'existe pas.
**
** CONTRAINTES :
**
** - Utiliser un tableau de char pour stocker la chaîne.
** - Utiliser une boucle pour parcourir la chaîne.
** - Parcourir la chaîne jusqu'à '\0'.
** - Comparer chaque caractère avec le caractère recherché.
** - Utiliser une variable permettant de savoir
**   si le caractère a été trouvé.
** - Ne pas utiliser strchr().
**
** OBJECTIFS :
**
** - Parcourir une chaîne de caractères.
** - Comparer des caractères.
** - Utiliser une condition dans une boucle.
** - Comprendre la logique de recherche.
** - Comprendre l'utilité d'une variable "trouve".
**
** QUESTION À TE POSER :
**
** Que dois-tu faire dès que tu trouves le caractère ?
**
** Que doit contenir ta variable "trouve" si le caractère
** a été trouvé ?
**
** BONUS :
**
** Affiche également la position du caractère trouvé.
**
** Exemple :
**
**     Chaîne : ordinateur
**     Caractère : d
**
** Résultat :
**
**     Le caractère existe.
**     Position : 6
*/