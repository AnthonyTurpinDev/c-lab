/*
** EXERCICE : Nombre premier
**
** Écrire un programme en langage C qui demande à l'utilisateur
** de saisir un nombre entier positif.
**
** Le programme doit déterminer si ce nombre est premier.
**
** RAPPEL :
**
** Un nombre premier est un nombre entier supérieur à 1 qui
** possède exactement deux diviseurs : 1 et lui-même.
**
** EXEMPLES :
**
** Entrée :
** 7
**
** Sortie :
** 7 est un nombre premier.
**
** Entrée :
** 12
**
** Sortie :
** 12 n'est pas un nombre premier.
**
** CAS PARTICULIERS :
**
** - 0 n'est pas un nombre premier.
** - 1 n'est pas un nombre premier.
** - 2 est un nombre premier.
**
** CONTRAINTES :
**
** - Demander un entier à l'utilisateur.
** - Utiliser une boucle pour rechercher les diviseurs.
** - Utiliser l'opérateur % pour vérifier la divisibilité.
** - Compter ou détecter les diviseurs trouvés.
** - Utiliser une condition pour déterminer le résultat.
** - Afficher clairement si le nombre est premier ou non.
**
** OBJECTIF :
**
** Apprendre à rechercher les diviseurs d'un nombre avec une
** boucle et à utiliser le modulo (%) pour tester la divisibilité.
**
** BONUS :
**
** - Optimiser la boucle pour ne tester que les diviseurs
**   jusqu'à la racine carrée du nombre.
** - Afficher les diviseurs trouvés.
** - Tester plusieurs nombres premiers et non premiers.
*/