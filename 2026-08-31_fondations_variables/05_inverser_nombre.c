/*
** EXERCICE : Inverser un nombre
**
** Écrire un programme qui demande à l'utilisateur de saisir
** un nombre entier positif.
**
** Le programme doit inverser l'ordre des chiffres du nombre
** puis afficher le résultat.
**
** EXEMPLES :
**
** Entrée : 321
** Sortie : 123
**
** Entrée : 12345
** Sortie : 54321
**
** Entrée : 700
** Sortie : 7
**
** CONTRAINTES :
**
** - Demander un nombre entier à l'utilisateur.
** - Utiliser une boucle pour parcourir les chiffres du nombre.
** - Utiliser l'opérateur % pour récupérer le dernier chiffre.
** - Utiliser la division entière / pour supprimer le dernier chiffre.
** - Construire progressivement le nombre inversé.
** - Afficher le nombre inversé.
**
** OBJECTIF :
**
** Comprendre comment extraire et reconstruire les chiffres
** d'un nombre entier en utilisant % et /.
**
** BONUS :
**
** - Gérer le cas où l'utilisateur saisit 0.
** - Tester le programme avec des nombres comportant des zéros.
*/