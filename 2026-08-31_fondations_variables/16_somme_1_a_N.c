/*
** EXERCICE : Somme de 1 à N
**
** Écrire un programme en langage C qui demande à l'utilisateur
** de saisir un nombre entier positif N.
**
** Le programme doit calculer la somme de tous les entiers
** compris entre 1 et N, puis afficher le résultat.
**
** EXEMPLES :
**
** Entrée :
** 5
**
** Calcul :
** 1 + 2 + 3 + 4 + 5
**
** Sortie :
** La somme est : 15
**
** AUTRE EXEMPLE :
**
** Entrée :
** 10
**
** Sortie :
** La somme est : 55
**
** CONTRAINTES :
**
** - Demander un entier positif N à l'utilisateur.
** - Utiliser une boucle pour parcourir les nombres de 1 à N.
** - Utiliser une variable pour stocker progressivement la somme.
** - Ajouter chaque nombre à la somme.
** - Afficher la somme finale avec printf.
** - Ne pas utiliser directement une formule mathématique
**   pour calculer le résultat.
**
** OBJECTIF :
**
** Apprendre à utiliser une variable d'accumulation dans une
** boucle et comprendre comment calculer progressivement
** un résultat.
**
** BONUS :
**
** - Gérer le cas où N est égal à 0.
** - Faire une deuxième version avec une boucle while.
*/