/*
** EXERCICE : Nombres premiers
**
** Écrire un programme en langage C qui demande à l'utilisateur
** de saisir un nombre entier positif N.
**
** Le programme doit afficher tous les nombres premiers compris
** entre 2 et N.
**
** RAPPEL :
**
** Un nombre premier est un nombre entier supérieur à 1 qui
** possède exactement deux diviseurs : 1 et lui-même.
**
** EXEMPLE :
**
** Entrée :
** 20
**
** Sortie :
** 2
** 3
** 5
** 7
** 11
** 13
** 17
** 19
**
** CONTRAINTES :
**
** - Demander un entier positif N à l'utilisateur.
** - Parcourir tous les nombres compris entre 2 et N.
** - Vérifier pour chaque nombre s'il est premier.
** - Utiliser une boucle pour rechercher les diviseurs.
** - Utiliser l'opérateur % pour tester la divisibilité.
** - Afficher uniquement les nombres premiers.
** - Ne pas utiliser de fonction toute faite permettant
**   de vérifier directement si un nombre est premier.
**
** OBJECTIF :
**
** Combiner plusieurs boucles et conditions afin de résoudre
** un problème plus complexe.
**
** BONUS :
**
** - Compter le nombre de nombres premiers trouvés.
** - Afficher le nombre total de nombres premiers.
** - Optimiser la recherche des diviseurs en limitant la boucle
**   jusqu'à la racine carrée du nombre.
*/