/*
** EXERCICE : Doubler un nombre
**
** FICHIER : 04_double.c
**
** OBJECTIF :
**
** Comprendre :
**
**     - les paramètres
**     - le mot-clé return
**     - la différence entre void et int
**
** CONSIGNE :
**
** Crée une fonction :
**
**     int double_number(int n)
**
** Cette fonction doit retourner le double du nombre reçu.
**
** EXEMPLES :
**
**     double_number(5)  → 10
**     double_number(20) → 40
**
**
** 💡 RÉFLEXION :
**
** La fonction reçoit un nombre grâce au paramètre :
**
**     int n
**
** Elle doit ensuite CALCULER le double de n
** et RETOURNER le résultat.
**
** Pose-toi ces questions :
**
** 1. Pourquoi la fonction est-elle de type int
**    et non void ?
**
** 2. Que doit retourner la fonction ?
**
** 3. Comment utiliser return ?
**
** 4. Comment récupérer le résultat dans main() ?
**
**
** ============================================
** DIFFÉRENCE ENTRE void ET int
** ============================================
**
** Une fonction :
**
**     void hello(void)
**
** effectue une action mais ne retourne pas de valeur.
**
** Une fonction :
**
**     int double_number(int n)
**
** retourne une valeur entière grâce à return.
**
**
** 🎯 OBJECTIFS À VALIDER :
**
** - Comprendre un paramètre.
** - Comprendre le rôle de return.
** - Comprendre qu'une fonction peut produire une valeur.
** - Comprendre la différence entre void et int.
** - Savoir récupérer le résultat d'une fonction dans main().
**
** ⚠️ IMPORTANT :
**
** Ne fais pas simplement afficher le résultat dans
** la fonction.
**
** La fonction doit RETOURNER le résultat.
*/