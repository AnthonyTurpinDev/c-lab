/*
** EXERCICE : Nombre premier
**
** Demander à l'utilisateur de saisir un nombre entier.
**
** Le programme doit déterminer si ce nombre est premier.
**
** RAPPEL :
**
** Un nombre premier est un entier supérieur à 1 qui possède
** exactement deux diviseurs :
**
** - 1
** - lui-même
**
** EXEMPLES :
**
** Entrée : 7
** Sortie : Le nombre est premier.
**
** Entrée : 10
** Sortie : Le nombre n'est pas premier.
**
** Entrée : 2
** Sortie : Le nombre est premier.
**
** Entrée : 1
** Sortie : Le nombre n'est pas premier.
**
** CONTRAINTES :
**
** - Utiliser une boucle.
** - Tester les différents diviseurs possibles.
** - Utiliser l'opérateur modulo %.
** - Gérer correctement les nombres inférieurs ou égaux à 1.
** - Afficher si le nombre est premier ou non.
**
** BONUS :
**
** - Créer une fonction is_prime() qui retourne 1 si le nombre
**   est premier et 0 sinon.
** - Optimiser la recherche des diviseurs en ne testant pas
**   tous les nombres jusqu'au nombre lui-même.
**
** OBJECTIF :
**
** S'entraîner à utiliser les boucles, le modulo et les conditions
** pour résoudre un problème mathématique simple.
*/