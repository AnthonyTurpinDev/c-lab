/*
** DÉFI : Find
**
** Écrire une fonction qui recherche une valeur dans un tableau
** d'entiers et retourne un pointeur vers la première occurrence.
**
** EXEMPLE :
**
** Tableau :
** 10 20 30 40 50
**
** Recherche :
** 30
**
** Résultat :
** Pointeur vers 30.
**
** CONTRAINTES :
**
** - Utiliser un pointeur pour parcourir le tableau.
** - Retourner l'adresse de l'élément trouvé.
** - Retourner NULL si la valeur n'existe pas.
** - Ne pas retourner l'indice.
** - Ne pas créer de tableau auxiliaire.
**
** RÈGLE DU DÉFI :
**
** Trouver seul comment retourner l'adresse de l'élément.
*/