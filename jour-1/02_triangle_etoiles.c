///Triangle d’étoiles — Boucles imbriquées

//Écrire un programme en langage C qui demande à l'utilisateur une hauteur `n`, puis affiche un triangle composé d'étoiles `*`.

//Chaque ligne doit contenir un nombre d'étoiles correspondant à son numéro de ligne.

//## Exemple

//Si l'utilisateur saisit :

//```text
//5
//```

//Le programme doit afficher :

//```text
//*
//**
//***
//**
//*****

//```

//## Contraintes

//* Demander la hauteur `n` à l'utilisateur.
//* Utiliser une première boucle pour parcourir les lignes.
//* Utiliser une deuxième boucle à l'intérieur de la première pour afficher les étoiles.
//* Utiliser `printf` pour afficher les étoiles.
//* Utiliser `printf("\n")` pour passer à la ligne suivante.
//* Ne pas afficher le triangle avec des `printf` écrits manuellement.

//## Objectif

//Comprendre le fonctionnement des **boucles imbriquées** en C et apprendre à contrôler le nombre de répétitions d'une boucle à l'intérieur d'une autre.
