/*
** EXERCICE : Convertisseur Celsius ↔ Fahrenheit
**
** Écrire un programme qui permet de convertir une température
** entre les degrés Celsius et les degrés Fahrenheit.
**
** Le programme doit afficher un petit menu permettant
** à l'utilisateur de choisir le type de conversion.
**
** MENU :
**
** 1. Celsius vers Fahrenheit
** 2. Fahrenheit vers Celsius
**
** Le programme demande ensuite la température à convertir
** et affiche le résultat.
**
** FORMULES :
**
** Celsius → Fahrenheit :
** F = (C * 9 / 5) + 32
**
** Fahrenheit → Celsius :
** C = (F - 32) * 5 / 9
**
** EXEMPLES :
**
** Choix : 1
** Température en Celsius : 25
** Résultat : 77 Fahrenheit
**
** Choix : 2
** Température en Fahrenheit : 68
** Résultat : 20 Celsius
**
** CONTRAINTES :
**
** - Afficher un menu à l'utilisateur.
** - Utiliser switch pour gérer le choix du menu.
** - Demander la température à convertir.
** - Utiliser les formules de conversion appropriées.
** - Afficher le résultat.
** - Prévoir un cas par défaut si l'utilisateur choisit
**   une option inexistante.
** - Utiliser des nombres décimaux pour permettre des résultats
**   plus précis.
**
** OBJECTIF :
**
** Pratiquer les menus, switch, les variables, les calculs
** arithmétiques et les nombres à virgule en langage C.
**
** BONUS :
**
** - Ajouter une option pour quitter le programme.
** - Permettre de réaliser plusieurs conversions sans relancer
**   le programme.
*/