/*
** EXERCICE : Factorielle
**
** Écrire un programme en langage C qui demande à l'utilisateur
** de saisir un nombre entier positif N.
**
** Le programme doit calculer la factorielle de N et afficher
** le résultat.
**
** La factorielle d'un nombre N correspond au produit de tous
** les entiers compris entre 1 et N.
**
** EXEMPLE :
**
** Entrée :
** 5
**
** Calcul :
** 5 x 4 x 3 x 2 x 1
**
** Sortie :
** 5! = 120
**
** AUTRE EXEMPLE :
**
** Entrée :
** 3
**
** Sortie :
** 3! = 6
**
** CAS PARTICULIER :
**
** La factorielle de 0 est égale à 1.
**
** Entrée :
** 0
**
** Sortie :
** 0! = 1
**
** CONTRAINTES :
**
** - Demander un entier positif N à l'utilisateur.
** - Utiliser une boucle pour calculer la factorielle.
** - Utiliser une variable pour stocker progressivement
**   le résultat.
** - Utiliser une multiplication à chaque étape.
** - Afficher le résultat final avec printf.
** - Ne pas utiliser de fonction de bibliothèque pour calculer
**   directement la factorielle.
**
** OBJECTIF :
**
** Comprendre l'utilisation d'une variable d'accumulation
** avec une boucle et pratiquer les multiplications successives.
**
** BONUS :
**
** - Faire une deuxième version avec une boucle while.
** - Vérifier que l'utilisateur ne saisit pas un nombre négatif.
** - Tester avec plusieurs valeurs.
*/