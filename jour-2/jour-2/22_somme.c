/*
** EXERCICE : Somme
**
** Écrire un programme en langage C qui demande à l'utilisateur
** de saisir un nombre entier positif N.
**
** Le programme doit calculer la somme de tous les nombres
** compris entre 1 et N.
**
** EXEMPLE :
**
** Entrée :
** 5
**
** Calcul :
** 1 + 2 + 3 + 4 + 5
**
** Sortie :
** Somme = 15
**
** AUTRE EXEMPLE :
**
** Entrée :
** 10
**
** Sortie :
** Somme = 55
**
** CONTRAINTES :
**
** - Demander un entier positif N à l'utilisateur.
** - Utiliser une boucle pour parcourir les nombres de 1 à N.
** - Utiliser une variable pour stocker la somme.
** - Ajouter chaque nombre à la somme.
** - Afficher le résultat final avec printf.
** - Ne pas utiliser directement une formule mathématique.
**
** OBJECTIF :
**
** Comprendre le principe d'accumulation avec une boucle
** et apprendre à conserver progressivement un résultat.
**
** BONUS :
**
** - Faire une version avec une boucle while.
** - Faire une version avec une boucle do...while.
** - Gérer le cas où N vaut 0.
*/