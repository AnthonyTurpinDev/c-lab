/*
** EXERCICE : Maximum
**
** Écrire un programme en langage C qui demande à l'utilisateur
** combien de nombres il souhaite saisir.
**
** Le programme doit ensuite demander chaque nombre et déterminer
** le plus grand nombre parmi toutes les valeurs saisies.
**
** EXEMPLE :
**
** Entrée :
** Combien de nombres ? 5
**
** Nombres :
** 12
** 7
** 25
** 3
** 18
**
** Sortie :
** Le maximum est : 25
**
** CONTRAINTES :
**
** - Demander le nombre de valeurs à saisir.
** - Utiliser une boucle pour saisir les nombres un par un.
** - Utiliser une variable pour mémoriser le maximum.
** - Comparer chaque nouveau nombre avec le maximum actuel.
** - Mettre à jour le maximum lorsqu'un nombre plus grand
**   est trouvé.
** - Afficher le maximum à la fin du programme.
** - Gérer le cas où l'utilisateur saisit 0 comme nombre
**   de valeurs.
**
** OBJECTIF :
**
** Apprendre à rechercher la plus grande valeur dans un ensemble
** de nombres en utilisant une boucle et des conditions.
**
** BONUS :
**
** - Trouver également le minimum.
** - Afficher la position du maximum.
** - Tester avec des nombres négatifs.
*/