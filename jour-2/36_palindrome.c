/*
** EXERCICE : Vérifier si une chaîne est un palindrome
**
** Écrire un programme en langage C qui demande à l'utilisateur
** de saisir une chaîne de caractères.
**
** Le programme doit déterminer si la chaîne est un palindrome.
**
** RAPPEL :
**
** Un palindrome est une chaîne qui se lit de la même manière
** de gauche à droite et de droite à gauche.
**
** EXEMPLES :
**
** Entrée :
** radar
**
** Sortie :
** "radar" est un palindrome.
**
** AUTRE EXEMPLE :
**
** Entrée :
** bonjour
**
** Sortie :
** "bonjour" n'est pas un palindrome.
**
** CONTRAINTES :
**
** - Déclarer un tableau de caractères pour stocker la chaîne.
** - Demander une chaîne à l'utilisateur.
** - Comparer les caractères situés aux deux extrémités
**   de la chaîne.
** - Avancer progressivement vers le centre de la chaîne.
** - Utiliser une boucle pour effectuer les comparaisons.
** - Utiliser une variable permettant de mémoriser si la chaîne
**   est un palindrome ou non.
** - Afficher clairement le résultat.
**
** ATTENTION :
**
** Pour cette première version, considérer que les espaces,
** les majuscules et les caractères spéciaux sont significatifs.
**
** EXEMPLE :
**
** "radar" → palindrome
** "Radar" → pas un palindrome
**
** OBJECTIF :
**
** Apprendre à manipuler les indices d'une chaîne de caractères
** et à comparer simultanément des caractères situés aux deux
** extrémités.
**
** BONUS :
**
** - Ignorer les majuscules/minuscules.
** - Ignorer les espaces.
** - Ignorer les caractères spéciaux.
** - Créer une fonction est_palindrome().
*/